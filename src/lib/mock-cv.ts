import type { AdminApplicationDetail } from "@/types/admin";

/**
 * Mock cv preview.
 */
function buildPreviewPdf(name: string, jobTitle: string): string {
  const safe = (value: string) =>
    value
      .replace(/[^\x20-\x7e]/g, "-")
      .replace(/\\/g, "\\\\")
      .replace(/\(/g, "\\(")
      .replace(/\)/g, "\\)");

  const stream = [
    "BT",
    "0.15 0.23 0.55 rg",
    "/F1 22 Tf",
    "56 790 Td",
    "(BrightCore) Tj",
    "0 -26 Td",
    "/F2 12 Tf",
    "0.35 0.38 0.45 rg",
    "(PREVIEW CV) Tj",
    "0 -44 Td",
    "/F1 18 Tf",
    "0.08 0.08 0.1 rg",
    `(${safe(name)}) Tj`,
    "0 -24 Td",
    "/F2 11 Tf",
    "0.35 0.38 0.45 rg",
    `(Application: ${safe(jobTitle)}) Tj`,
    "0 -40 Td",
    "/F1 12 Tf",
    "0.08 0.08 0.1 rg",
    "(This is a placeholder CV generated by the admin dashboard preview.) Tj",
    "0 -18 Td",
    "(The real PDF will be streamed from the protected BrightCore API.) Tj",
    "0 -18 Td",
    "(Sign in and connect the API to download an applicant's actual CV.) Tj",
    "ET",
  ].join("\n");

  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];

  objects.forEach((body, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  offsets.forEach((offset) => {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n`;
  pdf += `startxref\n${xrefStart}\n%%EOF`;

  return pdf;
}

export function downloadMockCv(application: AdminApplicationDetail) {
  const filename =
    application.cv?.filename ??
    `${application.full_name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-cv.pdf`;
  const blob = new Blob(
    [buildPreviewPdf(application.full_name, application.job.title)],
    { type: "application/pdf" },
  );
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");

  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1_000);
}
